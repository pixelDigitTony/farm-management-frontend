import { copyFile, cp, mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const workspace = path.dirname(root);
const backend = path.join(workspace, "farm-management-backend");
const pack = path.join(workspace, "design/landing-builder-2026-10-08/assets");
const contract = await readFile(path.join(backend, "src/validation/landing-page.ts"), "utf8");
await writeFile(
  path.join(root, "src/lib/product-availability.ts"),
  "// Generated from the backend availability contract. Run sync-landing-contract.mjs to update.\n" +
    (await readFile(path.join(backend, "src/lib/product-availability.ts"), "utf8")),
);
await mkdir(path.join(root, "src/lib/landing-page"), { recursive: true });
await writeFile(
  path.join(root, "src/lib/landing-page/schema.ts"),
  "// Generated by scripts/sync-landing-contract.mjs. Edit the backend schema and resync.\n" +
    contract,
);
if (process.argv.includes("--contracts-only")) process.exit(0);
const manifest = JSON.parse(await readFile(path.join(pack, "manifest.json"), "utf8"));
const assets = Object.fromEntries(
  manifest.assets.map((a) => [
    a.id,
    {
      url: "/landing-assets/" + a.defaultSrc,
      alt: a.alt,
      focalPoint: a.focalPoint,
      aspectRatio: "AUTO",
      width: a.width,
      height: a.height,
      sources: a.variants.map((v) => ({
        url: "/landing-assets/" + v.file,
        width: v.width,
        height: v.height,
      })),
    },
  ]),
);
const scenes = manifest.backgrounds.map((b) => ({
  id: b.sceneId,
  revision: 1,
  label: manifest.templates[b.template],
  glb: "/landing-assets/" + b.glb.replace("blender/", "models/"),
  poster: assets[b.posterAsset].url,
  mobilePoster:
    assets[b.mobilePosterAsset]?.url ??
    assets[b.posterAsset + "-mobile"]?.url ??
    assets[b.posterAsset].url,
  desktopCamera: b.cameraNodes.find((c) => /desktop/i.test(c.name))?.name ?? b.cameraNodes[0].name,
  mobileCamera: b.cameraNodes.find((c) => /mobile/i.test(c.name))?.name ?? b.cameraNodes[1]?.name,
  draco:
    b.extensionsUsed?.includes("KHR_draco_mesh_compression") ??
    ["haven-scenery", "farm-scenery"].includes(b.sceneId),
}));
const json = JSON.stringify({ assets, scenes }, null, 2) + "\n";
await writeFile(path.join(root, "src/lib/landing-page/assets.json"), json);
await writeFile(path.join(backend, "src/services/landing-assets.json"), json);
const publicRoot = path.join(root, "public/landing-assets");
const { default: sharp } = await import(
  pathToFileURL(createRequire(path.join(backend, "package.json")).resolve("sharp")).href
);
await mkdir(path.join(publicRoot, "previews"), { recursive: true });
for (const [id, file] of Object.entries({
  "bold-market": "01-bold-market",
  "editorial-studio": "02-editorial-studio",
  "architectural-escape": "03-architectural-escape",
  "everyday-boutique": "04-boutique-classic",
  "farm-and-market": "05-farm-and-market",
  "farm-and-market-ordering": "05-farm-and-market-ordering",
})) {
  await sharp(path.join(workspace, "design/landing-builder-2026-10-08/images", file + ".png"))
    .resize({ width: 960, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toFile(path.join(publicRoot, "previews", id + ".webp"));
}
await mkdir(path.join(publicRoot, "models"), { recursive: true });
await cp(path.join(pack, "web"), path.join(publicRoot, "web"), { recursive: true });
await cp(path.join(pack, "icons"), path.join(publicRoot, "icons"), { recursive: true });
await cp(
  path.join(root, "node_modules/three/examples/jsm/libs/draco/gltf"),
  path.join(publicRoot, "draco"),
  { recursive: true },
);
for (const b of manifest.backgrounds)
  await copyFile(path.join(pack, b.glb), path.join(publicRoot, "models", path.basename(b.glb)));
console.log("Synced validated schema, 36 responsive assets and 5 scene models.");
